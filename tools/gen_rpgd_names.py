#!/usr/bin/env python3
"""Regenerates AutoTRP/Data/RPGDNames.lua from a checkout of rpg-dialogue.

rpg-dialogue keeps its towns and throughlines inside its own private namespace, so
Auto TRP ships a copy of their display names (ids are what the saved data holds).

Usage: python3 tools/gen_rpgd_names.py /path/to/rpg-dialogue
"""
import glob, os, re, sys

root = sys.argv[1] if len(sys.argv) > 1 else "../rpg-dialogue"
towns, threads = {}, {}
for f in sorted(glob.glob(os.path.join(root, "RPGDialogue_*", "**", "*.lua"), recursive=True)):
    s = open(f, encoding="utf-8").read()
    for kind, store, field in (("Town", towns, "name"), ("Thread", threads, "title")):
        for m in re.finditer(r"P:%s\s*\{(.*?)\n\}" % kind, s, re.S):
            body = m.group(1)
            i = re.search(r'\bid\s*=\s*"([^"]+)"', body)
            n = re.search(r'\b%s\s*=\s*"([^"]+)"' % field, body)
            if i and n:
                store[i.group(1)] = n.group(1)

def lua(name, d):
    out = ["ns.RPGDNames.%s = {" % name]
    for k in sorted(d):
        out.append('  [%s] = %s,' % (lua_str(k), lua_str(d[k])))
    out.append("}")
    return "\n".join(out)

def lua_str(v):
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'

dest = os.path.join(os.path.dirname(__file__), "..", "AutoTRP", "Data", "RPGDNames.lua")
with open(dest, "w", encoding="utf-8") as fh:
    fh.write("-- Generated by tools/gen_rpgd_names.py from rpg-dialogue. Do not edit by hand.\n")
    fh.write("-- Display names for rpg-dialogue's town and throughline ids.\n")
    fh.write("local _, ns = ...\nns.RPGDNames = {}\n\n")
    fh.write(lua("towns", towns) + "\n\n" + lua("threads", threads) + "\n")
print("towns:", len(towns), "threads:", len(threads), "->", os.path.normpath(dest))
